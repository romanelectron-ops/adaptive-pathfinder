package androidbridge

import "github.com/apf/adaptive-pathfinder/internal/netutil"

// LinkHostWarning — предупреждение «эта ссылка роли «Выход» не сработает из другой сети».
//
// Живой инцидент 2026-09-29: экран «Выход» собирал ссылку на локальный адрес устройства
// (10.x.x.x, внутри сети раздачи/Wi-Fi) и подписывал её «можно передавать партнёру «Вход»» —
// а партнёр в ДРУГОЙ сети получал dial tcp ...: i/o timeout без единого намёка на причину:
// частный адрес существует только внутри своей сети и снаружи недостижим в принципе.
//
// Тонкая обёртка над netutil.LinkHostWarning, экспортируемая в Kotlin (gomobile принимает только
// экспортируемые функции пакета с простыми типами — string → String). Возвращает русский текст
// предупреждения либо "" (публичный IP / имя хоста — предупреждать не о чем). Чистая функция:
// не требует Init() и не трогает состояние моста, поэтому годится вызывать до любого запуска
// роли. Живёт в ОТДЕЛЬНОМ файле, а не внутри server_role.go, чтобы не смешиваться с жизненным
// циклом роли: классификация адреса от него не зависит.
//
// Контракт BuildServerLinkJSON ({"link":...} / {"error":...}) НЕ менялся — предупреждение
// запрашивается отдельным вызовом, разбор ответа на стороне Kotlin остаётся прежним.
func LinkHostWarning(host string) string {
	return netutil.LinkHostWarning(host)
}
