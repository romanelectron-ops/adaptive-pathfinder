// Package hotkey — глобальный системный хоткей аварийного стирания.
//
// P1.1 (docs/TZ_APF_ROADMAP_v1.2.md, находка аудита 2026-08-19): models.AppConfig.EmergencyHotkey
// годами показывался в UI как "Ctrl+Shift+F12" — рабочая аварийная защита, которую пользователь
// мог нажать в панике, — но ни один системный хоткей нигде не регистрировался. Кнопка была
// исключительно текстом. Этот пакет закрывает разрыв на Windows; на прочих платформах Register
// явно возвращает ErrUnsupported, а не делает вид, что подписался.
package hotkey

import "errors"

// ErrUnsupported — платформа не поддерживает глобальный системный хоткей (пока — только Windows).
var ErrUnsupported = errors.New("hotkey: глобальный системный хоткей не поддерживается на этой платформе")

// Manager — активная регистрация одного глобального хоткея. Возвращается только при
// err == nil — как и везде в Go, не вызывайте методы на Manager, если Register вернула ошибку.
type Manager interface {
	Unregister()
}

// Register разбирает комбинацию вида "ctrl+shift+F12" (регистр не важен, порядок модификаторов
// любой; поддержаны модификаторы ctrl/control/shift/alt/win/meta/super и клавиши F1-F24, A-Z,
// 0-9) и начинает слушать её нажатие в системе — даже когда окно приложения не в фокусе или
// свёрнуто в трей (весь смысл аварийного хоткея). onTrigger вызывается на выделенном потоке
// сообщений при каждом срабатывании — не выполняйте в нём длительную работу, только сигнал.
func Register(combo string, onTrigger func()) (Manager, error) {
	return register(combo, onTrigger)
}
