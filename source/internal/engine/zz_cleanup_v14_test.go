// zz_cleanup_v14_test.go — ТЗ v1.4, C-10 (лот L1b-TST): мета-тест «после прогона пакета
// живых горутин движка ноль».
//
// ПОЧЕМУ ИМЯ ФАЙЛА zz_*, А НЕ TestMain: пакет уже владеет одним TestMain
// (testmain_isolation_test.go, лот другого агента) — Go допускает только один TestMain
// на пакет, второй = ошибка компиляции. Единственный доступный этому лоту способ
// «выполниться после всех остальных тестов» без TestMain — обычный тест в файле, чьё имя
// сортируется последним по алфавиту среди файлов пакета (`go test` компилирует и
// перечисляет тесты в порядке файлов, а при ПОСЛЕДОВАТЕЛЬНОМ (не t.Parallel) прогоне
// внутри одного пакета выполняет их в этом же порядке одну за другой). "zz_" заведомо
// позже "engine_*", "testmain_*", "tor_*", "add_node_*" и "nodes_*"/"server_*"/"sweep*".
//
// ОГОВОРКА ПРО t.Parallel() (записана явно, не спрятана в комментарии): тест, вызвавший
// t.Parallel(), приостанавливается, и его ТЕЛО фактически выполняется только после того,
// как весь список тестов пакета (включая последовательные, в том числе этот zz-тест)
// исчерпан целиком — так работает t.Parallel в стандартном testing (родительский раннер
// откладывает все параллельные подтесты до конца собственного цикла и лишь тогда снимает
// барьер). Иными словами: серийный тест НИКОГДА не увидит эффект ещё не начавшегося
// параллельного теста, а параллельный тест, начавшийся ДО зимнего снимка (что тут
// невозможно, так как барьер снимается уже после zz), тоже не будет пойман. На момент
// написания в пакете ровно 2 файла с t.Parallel() (engine_coverage10_test.go,
// engine_coverage11_test.go — 3 теста), и все три вызывают e.runPostConnectAntiBlock/
// Canary/LeakTest СИНХРОННО (без `go`, без newTestEngineWithCleanup) — проверено чтением
// исходников при составлении этого лота, никакой горутины они сами не порождают и
// движков не оставляют. Если в будущем в пакете появится t.Parallel()-тест, создающий
// *Engine и не останавливающий его строго до возврата из функции, этот мета-тест его
// НЕ увидит — структурное ограничение модели parallel в testing, не баг сортировки
// имени файла. Записано также в result.md лота L1b-TST.
import (
	"os"
	"testing"
	"time"
)

// TestZZZ_NoEngineGoroutineLeak — после прогона пакета internal/engine ни одна горутина
// с методом *Engine в стеке не должна быть жива.
//
// Ретрай/ожидание до maxWait: у Stop() есть собственный wgWaitTimeout (15s) на
// завершение уже отслеживаемых (e.wg) горутин, но НЕотслеживаемые detached-горутины
// (`go func(){...}()` без goTracked/e.wg, если такие где-то остались) могут доживать
// после Stop() ещё какое-то небольшое время — как раз то, что этот тест обязан заметить.
func TestZZZ_NoEngineGoroutineLeak(t *testing.T) {
	const (
		maxWait   = 5 * time.Second
		pollEvery = 100 * time.Millisecond
	)

	var leaked []string
	deadline := time.Now().Add(maxWait)
	for {
		leaked = snapshotEngineGoroutines()
		if len(leaked) == 0 || time.Now().After(deadline) {
			break
		}
		time.Sleep(pollEvery)
	}

	if len(leaked) == 0 {
		t.Log("OK: 0 живых горутин движка (*Engine) после прогона пакета internal/engine")
		return
	}

	t.Logf("живых горутин движка после прогона пакета: %d (ожидалось 0, ждали до %v)", len(leaked), maxWait)
	for i, s := range leaked {
		t.Logf("--- утёкшая горутина движка #%d ---\n%s", i+1, s)
	}
	t.Log("контекст: см. result.md лота L1b-TST (ТЗ v1.4, C-10) — список тестов-кандидатов " +
		"на утечку и разбор причины; решение чинить/не чинить остаётся за оркестратором, " +
		"этот тест только фиксирует факт по фактическому стеку горутин.")

	// Мягкий режим по умолчанию (см. постановку лота): существующие тесты пакета могут
	// оставлять движки незакрытыми (это и есть предмет отчёта, не повод красить весь
	// пакет). APF_STRICT_LEAKS=1 переключает тест в жёсткий режим — пригодится, когда
	// (если) оркестратор решит запретить регресс по этому пункту.
	if os.Getenv("APF_STRICT_LEAKS") == "1" {
		t.Fatalf("APF_STRICT_LEAKS=1: %d горутин(ы) *Engine пережили прогон пакета", len(leaked))
	}
}
