package netutil

import "net"

// ReserveFreePort просит ОС выделить свободный TCP-порт на 127.0.0.1, сразу закрывает
// временный listener и возвращает номер порта. Нужен там, где порт передаётся ВНЕШНЕМУ
// потребителю, который не может сам сообщить, что ему досталось при "слушай :0" — например,
// windowsServerRunner запускает sing-box отдельным процессом, а AndroidServerRunner поднимает
// sing-box in-process, но через собственный (не переиспользуемый напрямую) сетевой стек
// libbox. В обоих случаях единственный способ узнать порт заранее — зарезервировать его
// здесь и передать номер в конфигурацию. Стандартный приём с небольшим (и принятым) окном
// гонки между освобождением и повторным использованием порта.
func ReserveFreePort() (int, error) {
	ln, err := net.Listen("tcp", "127.0.0.1:0")
	if err != nil {
		return 0, err
	}
	port := ln.Addr().(*net.TCPAddr).Port
	ln.Close()
	return port, nil
}
